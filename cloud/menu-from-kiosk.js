#!/usr/bin/env node
/* Builds cloud/src/kiosk-menu.js: the price book the Worker uses to check "Pay on my phone"
   carts. It is read straight out of drink-kiosk.html (the same menu the kiosk screen prices
   from), so a price change on the kiosk reaches the Worker on the next build/deploy.
   Fails loudly if the kiosk page no longer looks the way this script expects: a stale or
   missing price book only ever makes the Worker refuse a phone payment (the customer then
   pays at the window), it can never make it accept a wrong price.
   Run by build.js; can also be run alone:  node menu-from-kiosk.js */
const fs = require("fs"), path = require("path"), vm = require("vm");

function extract(html) {
  const a = html.indexOf("/* ============ MENU DATA ============ */");
  const b = html.indexOf("let MENU = THIRSTY_MENU;");
  if (a < 0 || b < 0 || b < a) throw new Error("menu-from-kiosk: menu markers not found in drink-kiosk.html");
  const code = html.slice(a, b) + "\n;({THIRSTY_MENU, SECRET_MENU});";
  const { THIRSTY_MENU, SECRET_MENU } = vm.runInNewContext(code, {}, { timeout: 2000 });
  const all = { ...THIRSTY_MENU, secret: SECRET_MENU };
  const cents = (n, where) => {
    if (typeof n !== "number" || !isFinite(n)) throw new Error("menu-from-kiosk: bad price at " + where);
    return Math.round(n * 100);
  };
  const cats = {};
  for (const [key, cat] of Object.entries(all)) {
    if (!cat || !Array.isArray(cat.items)) throw new Error("menu-from-kiosk: bad category " + key);
    cats[key] = {
      items: cat.items.map(it => ({ id: String(it.id), name: String(it.name), price: cents(it.price, key + "/" + it.id) })),
      options: (cat.options || []).map(o => ({
        key: String(o.key), multi: !!o.multi,
        choices: o.choices.map(c => ({ name: String(c.name), d: cents(c.d, key + "/" + o.key + "/" + c.name) })),
      })),
    };
  }
  // Upsell add-ons ("Make it a Float" etc.) are written inline in buildUpsellOffers().
  const fnAt = html.indexOf("function buildUpsellOffers(");
  const fnEnd = html.indexOf("function showUpsell(", fnAt);
  if (fnAt < 0 || fnEnd < 0) throw new Error("menu-from-kiosk: buildUpsellOffers() not found");
  const body = html.slice(fnAt, fnEnd);
  const upsells = [...body.matchAll(/price:\s*([\d.]+),\s*mod:\s*"([^"]+)"/g)].map(m => ({ mod: m[2], price: Math.round(parseFloat(m[1]) * 100) }));
  if (upsells.length !== 3) throw new Error("menu-from-kiosk: expected 3 upsell offers, found " + upsells.length);
  if (!/line\.unit = \+\(line\.unit \+ offer\.price\)\.toFixed\(2\)/.test(html) || !/line\.mods = \[\.\.\.\(line\.mods \|\| \[\]\), offer\.mod\]/.test(html))
    throw new Error("menu-from-kiosk: commitUpsell() no longer appends the add-on as expected");
  // Snap-a-pic lines are priced from Pour Decisions in dirtysodas/lemonades (snapToLine()).
  if (!html.includes('i.id==="pour-decisions"') || !html.includes('const catKey = lemon ? "lemonades" : "dirtysodas";'))
    throw new Error("menu-from-kiosk: snapToLine() pricing changed; update cloud/src/pricebook.js");
  // AI / specials lines are priced from the category's BYO item, else its cheapest (openAIDrink()).
  if (!html.includes("cat.items.find(i => /build your own|pour decisions|byo/i.test(i.name + i.id)) ||"))
    throw new Error("menu-from-kiosk: openAIDrink() pricing changed; update cloud/src/pricebook.js");
  return { cats, upsells, snap: { itemId: "pour-decisions", cats: ["dirtysodas", "lemonades"] } };
}

function writeMenu(root = path.join(__dirname, "..")) {
  const html = fs.readFileSync(path.join(root, "drink-kiosk.html"), "utf8");
  const light = path.join(root, "drink-kiosk-light.html");
  if (fs.existsSync(light) && fs.readFileSync(light, "utf8") !== html)
    console.warn("menu-from-kiosk: WARNING drink-kiosk-light.html differs from drink-kiosk.html; prices come from drink-kiosk.html");
  const menu = extract(html);
  const out = "/* GENERATED by cloud/menu-from-kiosk.js from drink-kiosk.html. Do not edit by hand;\n" +
    "   change the kiosk menu and rebuild (node build.js). Prices are in cents. */\n" +
    "export const KIOSK_MENU = " + JSON.stringify(menu, null, 1) + ";\n";
  fs.writeFileSync(path.join(__dirname, "src", "kiosk-menu.js"), out);
  return menu;
}

module.exports = { extract, writeMenu };
if (require.main === module) {
  const m = writeMenu();
  console.log("kiosk-menu.js written:", Object.keys(m.cats).length, "categories,",
    Object.values(m.cats).reduce((a, c) => a + c.items.length, 0), "items");
}

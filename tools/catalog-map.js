#!/usr/bin/env node
/* tools/catalog-map.js: keep catalog-map.json in step with the kiosk menu, and print the gap report.

   catalog-map.json maps every kiosk drink, size and add-on key to the Clover item or modifier id that prices it. The kiosk menu lives
   in drink-kiosk.html (the page); this tool reads it (the same extractor the cloud price book uses) and lists every key.
   IDs are NEVER invented: a key with "clover": null is unmapped and /quote refuses any cart that touches it.

     node tools/catalog-map.js            add new menu keys (clover: null), drop keys no longer on the menu, keep every id already filled in,
                                          rewrite catalog-map.json and catalog-gap-report.md
     node tools/catalog-map.js --check    exit 1 when the map lists different keys than the menu (ids may be null); writes nothing

   Key scheme: items are catKey/itemId; options are catKey + option key + choice name; floats are the attach-prompt "Float: <cap>" mods. */
"use strict";
const fs = require("fs");
const path = require("path");
const { extract } = require("../cloud/menu-from-kiosk.js");

const ROOT = path.resolve(__dirname, "..");
const MAP = path.join(ROOT, "catalog-map.json"), REPORT = path.join(ROOT, "catalog-gap-report.md");

function build(existing) {
  const menu = extract(fs.readFileSync(path.join(ROOT, "drink-kiosk.html"), "utf8"));
  const old = (existing && existing.categories) || {};
  const out = { version: 1, note: "Fill in 'clover' with the Clover item / modifier id. null = unmapped: /quote refuses carts that use it. Run: node tools/catalog-map.js", categories: {}, floats: [] };
  for (const [catKey, cat] of Object.entries(menu.cats)) {
    const prev = old[catKey] || { items: {}, options: [] };
    const items = {};
    for (const it of cat.items) items[it.id] = { name: it.name, kioskCents: it.price, clover: (prev.items[it.id] && prev.items[it.id].clover) || null };
    const options = cat.options.map(o => {
      const po = (prev.options || []).find(x => x.key === o.key);
      return { key: o.key, multi: !!o.multi, choices: o.choices.map(c => {
        const pc = po && (po.choices || []).find(x => x.name === c.name);
        return { name: c.name, kioskCents: c.d, clover: (pc && pc.clover) || null };
      }) };
    });
    out.categories[catKey] = { items, options };
  }
  for (const u of menu.upsells) {
    const pf = ((existing && existing.floats) || []).find(f => f.mod === u.mod);
    out.floats.push({ mod: u.mod, kioskCents: u.price, clover: (pf && pf.clover) || null });
  }
  return out;
}
const keysOf = m => {
  const k = [];
  for (const [c, cat] of Object.entries(m.categories || {})) {
    for (const id of Object.keys(cat.items || {})) k.push(`item ${c}/${id}`);
    for (const o of cat.options || []) for (const ch of o.choices) k.push(`mod ${c}/${o.key}/${ch.name}`);
  }
  for (const f of m.floats || []) k.push(`float ${f.mod}`);
  return k.sort();
};

function gapReport(map) {
  const lines = ["# Catalog gap report", "", "Generated by `node tools/catalog-map.js`. Do not edit by hand.", "",
    "`/quote` prices a cart only from Clover ids listed in `catalog-map.json`. Every key below still has `\"clover\": null`; until Nick fills it in, a cart that uses it is refused",
    "and the kiosk keeps using the legacy order path (window payment only). Nothing here is guessed: look the id up in the Clover dashboard (Inventory) or via the API and paste it in.", ""];
  let nItems = 0, nMods = 0, tItems = 0, tMods = 0;
  const body = [];
  for (const [c, cat] of Object.entries(map.categories)) {
    const items = Object.entries(cat.items), un = items.filter(([, v]) => !v.clover);
    tItems += items.length; nItems += un.length;
    const optLines = [];
    for (const o of cat.options) {
      const ucs = o.choices.filter(ch => !ch.clover);
      tMods += o.choices.length; nMods += ucs.length;
      if (ucs.length) optLines.push(`  - option \`${o.key}\` (${ucs.length} of ${o.choices.length} unmapped): ${ucs.map(ch => ch.name + " (" + (ch.kioskCents / 100).toFixed(2) + ")").join("; ")}`);
    }
    if (un.length || optLines.length) {
      body.push(`## ${c}`, "", un.length ? `- items (${un.length} of ${items.length} unmapped): ${un.map(([id, v]) => `\`${id}\` ${v.name} ($${(v.kioskCents / 100).toFixed(2)})`).join("; ")}` : "- items: all mapped", ...optLines, "");
    }
  }
  const uf = map.floats.filter(f => !f.clover); tMods += map.floats.length; nMods += uf.length;
  if (uf.length) body.push("## floats (attach prompt)", "", ...uf.map(f => `- \`${f.mod}\` ($${(f.kioskCents / 100).toFixed(2)})`), "");
  lines.push(`**Unmapped: ${nItems} of ${tItems} items, ${nMods} of ${tMods} modifier keys.**`, "",
    "A modifier id is per Clover modifier, not per key: the same Clover modifier (for example \"Dr Pepper\") may be used for the same choice in several categories.", "", ...body);
  return lines.join("\n") + "\n";
}

if (require.main === module) {
  const existing = fs.existsSync(MAP) ? JSON.parse(fs.readFileSync(MAP, "utf8")) : null;
  const next = build(existing);
  if (process.argv.includes("--check")) {
    if (!existing) { console.error("catalog-map.json is missing: run node tools/catalog-map.js"); process.exit(1); }
    const a = keysOf(existing), b = keysOf(next);
    const missing = b.filter(k => !a.includes(k)), extra = a.filter(k => !b.includes(k));
    if (missing.length || extra.length) { console.error(`catalog-map.json is out of step with the kiosk menu: ${missing.length} new key(s) (${missing.slice(0, 3).join("; ")}), ${extra.length} removed key(s). Run: node tools/catalog-map.js`); process.exit(1); }
    const ids = [];
    for (const c of Object.values(existing.categories)) { for (const v of Object.values(c.items)) if (v.clover) ids.push(v.clover); for (const o of c.options) for (const ch of o.choices) if (ch.clover) ids.push(ch.clover); }
    for (const id of ids) if (!/^[A-Za-z0-9]{8,20}$/.test(id)) { console.error("catalog-map.json has a malformed Clover id: " + id); process.exit(1); }
    console.log(`catalog-map.json matches the kiosk menu (${b.length} keys, ${ids.length} mapped)`);
  } else {
    fs.writeFileSync(MAP, JSON.stringify(next, null, 1) + "\n");
    fs.writeFileSync(REPORT, gapReport(next));
    console.log(`catalog-map.json: ${keysOf(next).length} keys; gap report written`);
  }
}
module.exports = { build, keysOf, gapReport };

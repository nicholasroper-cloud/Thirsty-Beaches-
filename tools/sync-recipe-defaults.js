#!/usr/bin/env node
/* tools/sync-recipe-defaults.js — what a NAMED drink is pre-filled with on the kiosk.
   A signature drink's recipe base (the first ingredient in recipes.json) and its soft-serve cap are pre-selected so the
   customer does not re-pick what the name already says. The result is a small data block written into drink-kiosk.html
   (and the identical drink-kiosk-light.html) between the RECIPE_DEFAULTS markers.
   Pour Decisions and Build Your Own Float are left blank on purpose (they are the build-your-own items).
   Usage:  node tools/sync-recipe-defaults.js           rewrite the block in both pages
           node tools/sync-recipe-defaults.js --check   exit 1 if the block is out of date (tests/kiosk/menu.js runs this) */
"use strict";
const fs = require("fs");
const path = require("path");
const vm = require("vm");
const ROOT = path.resolve(__dirname, "..");
const BEGIN = "/* RECIPE_DEFAULTS:BEGIN (generated by tools/sync-recipe-defaults.js; do not edit by hand) */";
const END = "/* RECIPE_DEFAULTS:END */";
const norm = s => String(s || "").toLowerCase().replace(/[^a-z0-9]+/g, "");
/* recipes.json spells ingredients one way, the kiosk menu another */
const ALIAS = { coke: "Coca-Cola", dietcoke: "Diet Coke", mountaindew: "Mountain Dew", dietmountaindew: "Diet Mtn Dew", orangesoda: "Fanta Orange", lemonade: "Classic Lemonade" };
/* floats have no ingredient list in recipes.json: their soft-serve cap comes from the build card ("Pineapple soft serve over your soda", "Vanilla soft serve on top") */
const FLOAT_DEFAULTS = { "beached-whale": { cap: "Pineapple soft serve" }, "swole-patrol": { cap: "Vanilla" }, "riptide-float": { cap: "Vanilla" }, "cold-front": { base: "Dr Pepper" } };
const BYO = new Set(["pour-decisions", "byo-float"]);

function loadMenu(html) {
  const a = html.indexOf("/* ============ MENU DATA ============ */"), b = html.indexOf("let MENU = THIRSTY_MENU;");
  if (a < 0 || b < a) throw new Error("menu markers not found in drink-kiosk.html");
  const code = html.slice(a, b).replace(/\/\* RECIPE_DEFAULTS:BEGIN[\s\S]*?RECIPE_DEFAULTS:END \*\//, "const RECIPE_DEFAULTS = {};");
  return vm.runInNewContext(code + "\n;({THIRSTY_MENU})", {}, { timeout: 2000 }).THIRSTY_MENU;
}
function compute(html, recipes) {
  const menu = loadMenu(html), out = {};
  for (const cat of Object.values(menu)) {
    const baseOpt = cat.options.find(o => o.key === "base");
    for (const it of cat.items) {
      if (BYO.has(it.id)) continue;
      const d = { ...(FLOAT_DEFAULTS[it.id] || {}) };
      const r = recipes[it.name];
      const first = r && r.i && r.i[0];
      if (baseOpt && first && !d.base && !/^blended/i.test(first)) {
        const want = norm(ALIAS[norm(first)] || first);
        const ch = baseOpt.choices.find(c => norm(c.name) === want);
        if (ch) d.base = ch.name;
      }
      if (Object.keys(d).length) out[it.id] = d;
    }
  }
  return out;
}
function block(defaults) {
  const lines = Object.keys(defaults).sort().map(k => " " + JSON.stringify(k) + ":" + JSON.stringify(defaults[k]));
  return BEGIN + "\nconst RECIPE_DEFAULTS = {\n" + lines.join(",\n") + "\n};\n" + END;
}
function apply(html, recipes) {
  const re = /\/\* RECIPE_DEFAULTS:BEGIN[\s\S]*?RECIPE_DEFAULTS:END \*\//;
  if (!re.test(html)) throw new Error("RECIPE_DEFAULTS markers not found");
  return html.replace(re, () => block(compute(html, recipes)));
}
module.exports = { compute, block, apply, loadMenu };
if (require.main === module) {
  const recipes = JSON.parse(fs.readFileSync(path.join(ROOT, "recipes.json"), "utf8")).recipes;
  const check = process.argv.includes("--check");
  let bad = 0;
  // drink-kiosk-light.html is a byte-for-byte copy of drink-kiosk.html (publish-menu.command copies one to the other)
  const fp = path.join(ROOT, "drink-kiosk.html"), lp = path.join(ROOT, "drink-kiosk-light.html");
  const html = fs.readFileSync(fp, "utf8"), next = apply(html, recipes);
  if (next !== html || fs.readFileSync(lp, "utf8") !== next) {
    if (check) { console.error("RECIPE_DEFAULTS is out of date, or the light page differs (run node tools/sync-recipe-defaults.js)"); bad = 1; }
    else { fs.writeFileSync(fp, next); fs.writeFileSync(lp, next); console.log("updated drink-kiosk.html and drink-kiosk-light.html"); }
  }
  if (!bad && check) console.log("recipe defaults: up to date");
  process.exit(bad);
}
